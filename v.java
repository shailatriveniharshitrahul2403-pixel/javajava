public class v {
    public static void main(String[] args) {
        // 6-row high ULTRA-BOLD solid blocks
        String[][] boldAlphabet = {
            // V (0)
            {"███     ███", "███     ███", " ███   ███ ", "  ███ ███  ", "   █████   ", "    ███    "},
            // I (1)
            {"█████████", "   ███   ", "   ███   ", "   ███   ", "   ███   ", "█████████"},
            // J (2)
            {"   ██████", "      ███", "      ███", "      ███", "███   ███", " ███████ "},
            // A (3)
            {"   ████   ", "  ██████  ", " ███  ███ ", "██████████", "███    ███", "███    ███"},
            // Y (4)
            {"███    ███", " ███  ███ ", "  ██████  ", "   ████   ", "   ████   ", "   ████   "},
            // E (5)
            {"██████████", " ███      ", " ███████  ", " ███      ", " ███      ", "██████████"},
            // T (6)
            {"██████████", "   ████   ", "   ████   ", "   ████   ", "   ████   ", "   ████   "},
            // Space (7)
            {"    ", "    ", "    ", "    ", "    ", "    "},
            // P (8)
            {"█████████ ", " ███   ███", " █████████", " ███      ", " ███      ", " ███      "},
            // N (9)
            {"███    ███", "████   ███", "█████████ ", "███ ██████", "███  █████", "███    ███"},
            // D (10)
            {"████████  ", " ███   ███ ", " ███    ███", " ███    ███", " ███   ███ ", "████████  "}
        };

        // Spelling order: V I J A Y E T A [space] P A N D E Y
        int[] nameIndices = {0, 1, 2, 3, 4, 5, 6, 3, 7, 8, 3, 9, 10, 5, 4};

        // Print row by row so they sit next to each other
        for (int row = 0; row < 6; row++) {
            for (int index : nameIndices) {
                System.out.print(boldAlphabet[index][row] + "  "); // 2 spaces spacing
            }
            System.out.println();
        }
    }
}
